"""The exportable improvement report.

Markdown rather than a generated PDF: it renders on GitHub, pastes into a
document, converts with pandoc, and prints from a browser, without this
service carrying a PDF toolchain it would otherwise never use.

The nine sections are README section 4.9's, in its order. The last one is the
point of the whole exercise: a report that listed findings and recommendations
without stating what was assumed, what could not be verified and what has not
been measured would read as far more authoritative than it is.
"""

from __future__ import annotations

from datetime import datetime

from app.schemas.architecture import ArchitectureView
from app.schemas.comparison import StackComparison, StackVerdict
from app.schemas.findings import DetectedBy, FindingKind, FindingsReport
from app.schemas.project import Claim, ProjectProfile
from app.schemas.recommendation import RecommendationReport
from app.schemas.roadmap import Roadmap


def _claim(claim: Claim | None) -> str:
    if claim is None:
        return "_Not identified._"
    if claim.evidence:
        page = claim.evidence[0].page
        return f"{claim.value} _(report, p{page})_"
    return f"{claim.value} _(inferred)_"


def _claim_list(claims: list[Claim], empty: str) -> str:
    if not claims:
        return f"_{empty}_"
    return "\n".join(f"- {_claim(c)}" for c in claims)


def _inline(claims: list[Claim], empty: str) -> str:
    if not claims:
        return f"_{empty}_"
    return ", ".join(
        f"{c.value}"
        + (f" (p{c.evidence[0].page})" if c.evidence else " (inferred)")
        for c in claims
    )


def render_markdown(
    *,
    filename: str,
    created_at: datetime,
    page_count: int,
    provider: str,
    model: str,
    profile: ProjectProfile,
    findings: FindingsReport,
    recommendations: RecommendationReport,
    comparison: StackComparison,
    architecture: ArchitectureView | None,
    roadmap: Roadmap,
    warnings: list[str],
) -> str:
    out: list[str] = []
    add = out.append

    add(f"# Improvement report: {profile.title.value}")
    add("")
    add(
        f"Generated by ProjectRevive AI on "
        f"{created_at.strftime('%Y-%m-%d')} from `{filename}` "
        f"({page_count} pages)."
    )
    add("")
    if provider == "mock":
        add(
            "> **No language model was used.** The project profile below comes "
            "from keyword matching, not comprehension. The weaknesses, gaps "
            "and recommendations come from deterministic rules and a curated "
            "knowledge base, and are unaffected by this."
        )
    else:
        add(f"> Analysis model: `{model}`.")
    add("")

    # --- 1 -----------------------------------------------------------------
    add("## 1. Original project summary")
    add("")
    add(f"**Title.** {_claim(profile.title)}")
    add("")
    add(f"**Domain.** {_claim(profile.domain)}")
    add("")
    add("**Problem.**")
    add("")
    add(f"> {profile.problem_statement.value}")
    add("")
    if profile.objectives:
        add("**Objectives.**")
        add("")
        add(_claim_list(profile.objectives, ""))
        add("")

    counts = profile.counts_by_source()
    add(
        f"Of {counts['total']} extracted facts, {counts['stated']} "
        f"{'is' if counts['stated'] == 1 else 'are'} stated in the report with "
        f"a verified citation and {counts['inferred']} "
        f"{'is' if counts['inferred'] == 1 else 'are'} inferred."
    )
    add("")

    # --- 2 -----------------------------------------------------------------
    add("## 2. Extracted methodology")
    add("")
    add(f"**Algorithms.** {_inline(profile.algorithms, 'None identified.')}")
    add("")
    add(f"**Languages.** {_inline(profile.stack.languages, 'None identified.')}")
    add("")
    add(f"**Libraries.** {_inline(profile.stack.libraries, 'None identified.')}")
    add("")
    add(f"**Metrics.** {_inline(profile.evaluation.metrics, 'None reported.')}")
    add("")
    add(
        "**Validation.** "
        f"{_claim(profile.evaluation.validation_strategy)}"
    )
    add("")
    if profile.stated_limitations:
        add("**Limitations the authors stated themselves.**")
        add("")
        add(_claim_list(profile.stated_limitations, ""))
        add("")

    # --- 3 -----------------------------------------------------------------
    add("## 3. Identified weaknesses and gaps")
    add("")
    if not findings.findings:
        add("_No weaknesses or gaps were detected._")
        add("")
    else:
        severity = findings.by_severity()
        sources = findings.counts_by_source()
        add(
            f"{sources['total']} findings: {severity['high']} high, "
            f"{severity['medium']} medium, {severity['low']} low. "
            f"{sources['rule']} came from deterministic rules that can be "
            f"read and checked; {sources['model']} are model judgements worth "
            "verifying."
        )
        add("")
        for finding in findings.findings:
            kind = "weakness" if finding.kind is FindingKind.WEAKNESS else "gap"
            origin = (
                "rule" if finding.detected_by is DetectedBy.RULE else "model"
            )
            add(
                f"### {finding.title}"
            )
            add("")
            add(
                f"`{finding.severity.value}` · `{kind}` · "
                f"`{finding.category.value}` · detected by {origin}"
            )
            add("")
            add(finding.explanation)
            add("")
            for item in finding.evidence:
                add(f"> “{item.quote}” — p{item.page}")
                add("")
            if finding.searched_for:
                add(f"_{finding.searched_for}_")
                add("")

    # --- 4 -----------------------------------------------------------------
    add("## 4. Ranked recommendations")
    add("")
    add(
        "Scores are a weighted sum of relevance, feasibility and an estimated "
        "impact, minus effort and cost. They are a ranking device, not a "
        "measurement."
    )
    add("")
    for index, item in enumerate(recommendations.recommendations, start=1):
        add(f"### {index}. {item.title}")
        add("")
        add(
            f"`score {item.score.final:.2f}` · `{item.complexity.value} effort` "
            f"· `{item.cost.value} cost`"
        )
        add("")
        add(f"**Why.** {item.reason}")
        add("")
        if item.addresses_findings:
            add(f"**Addresses.** {'; '.join(item.addresses_findings)}")
            add("")
        for quote in item.evidence[:1]:
            add(f"> “{quote.quote}” — p{quote.page}")
            add("")
        add(f"**Currently.** {item.current_approach}")
        add("")
        add(f"**Proposed.** {item.proposed_approach}")
        add("")
        add("**Expected benefits.**")
        add("")
        for benefit in item.expected_benefits:
            add(f"- {benefit}")
        add("")
        add("**Trade-offs.**")
        add("")
        for trade in item.trade_offs:
            add(f"- {trade}")
        add("")
        add("**Steps.**")
        add("")
        for step_index, step in enumerate(item.implementation_steps, start=1):
            add(f"{step_index}. {step}")
        add("")
        add(f"**How to check it worked.** {item.validation_method}")
        add("")

    # --- 5 -----------------------------------------------------------------
    add("## 5. Technology comparison")
    add("")
    keep = comparison.of(StackVerdict.KEEP)
    added = comparison.of(StackVerdict.ADD)
    replaced = comparison.of(StackVerdict.REPLACE)

    add("| Technology | Verdict | Reason |")
    add("| --- | --- | --- |")
    for entry in [*keep, *added, *replaced]:
        page = f" (p{entry.evidence[0].page})" if entry.evidence else ""
        reason = entry.rationale.replace("\n", " ").replace("|", "/")
        add(f"| `{entry.name}`{page} | {entry.verdict.value} | {reason} |")
    add("")
    for note in comparison.notes:
        add(f"- _{note}_")
    add("")

    # --- 6 -----------------------------------------------------------------
    add("## 6. Proposed architecture")
    add("")
    if architecture is None:
        add("_No architecture was generated for this analysis._")
        add("")
    else:
        add("**As described in the report**")
        add("")
        add("```mermaid")
        add(architecture.current_mermaid)
        add("```")
        add("")
        add("**With the recommendations applied**")
        add("")
        add("```mermaid")
        add(architecture.proposed_mermaid)
        add("```")
        add("")
        for note in architecture.notes:
            add(f"- _{note}_")
        add("")

    # --- 7 -----------------------------------------------------------------
    add("## 7. Development roadmap")
    add("")
    mix = roadmap.complexity_mix()
    add(
        f"{roadmap.task_count} tasks across {len(roadmap.phases)} phases: "
        f"{mix['low']} low, {mix['medium']} medium, {mix['high']} high "
        "complexity."
    )
    add("")
    for phase in roadmap.phases:
        add(f"### Phase {phase.order}: {phase.title}")
        add("")
        add(f"_{phase.rationale}_")
        add("")
        for task in phase.tasks:
            add(f"- **{task.title}** (`{task.complexity.value}`)")
            if task.dependencies:
                add(f"  - Needs: {', '.join(task.dependencies)}")
            add(f"  - Done when: {task.validation}")
        add("")
    for note in roadmap.notes:
        add(f"- _{note}_")
    add("")

    # --- 8 -----------------------------------------------------------------
    add("## 8. Testing and evaluation plan")
    add("")
    add(
        "Each recommendation carries its own check. Taken together these are "
        "the plan, in the order the roadmap applies them."
    )
    add("")
    add("| Change | How to tell it worked |")
    add("| --- | --- |")
    for phase in roadmap.phases:
        for task in phase.tasks:
            check = task.validation.replace("\n", " ").replace("|", "/")
            add(f"| {task.title} | {check} |")
    add("")
    add(
        "Record the metric before and after each change. A change that cannot "
        "be shown to have helped should be reverted, not kept because it "
        "sounded reasonable."
    )
    add("")

    # --- 9 -----------------------------------------------------------------
    add("## 9. Assumptions and limitations")
    add("")
    add("**What this report is not.**")
    add("")
    add(
        "- Relevance here is a judgement about appropriateness, not an "
        "observed outcome. No recommendation in this report has been applied "
        "to this project and measured."
    )
    add(
        "- The expected impact behind each score is a hand-written estimate "
        "in a curated knowledge base, identical for every project matching "
        "that entry. It has not been measured."
    )
    add(
        "- Nothing here was learned from usage data. There is no interaction "
        "data and no model was trained on one."
    )
    add("")

    add("**Assumptions made about your project.**")
    add("")
    for assumption in recommendations.constraints.assumptions:
        add(f"- {assumption}")
    add("")

    if recommendations.excluded:
        add("**Ruled out by those assumptions.**")
        add("")
        for item in recommendations.excluded:
            add(f"- {item}")
        add("")

    if warnings:
        add("**Caveats raised during analysis.**")
        add("")
        for warning in warnings:
            add(f"- {warning}")
        add("")

    add("**How the evidence was handled.**")
    add("")
    add(
        "- Every finding marked as being in the report quotes it, and each "
        "quote was checked against the page it cites. Citations that could "
        "not be verified were discarded rather than shown."
    )
    add(
        "- Gaps state what was searched for, because an absence cannot be "
        "quoted and you should be able to judge whether the search was "
        "reasonable."
    )
    add("")

    return "\n".join(out).rstrip() + "\n"
